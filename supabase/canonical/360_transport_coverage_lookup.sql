CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA extensions;

-- ---------------------------------------------------------------------------
-- 1) Tabla: copia plana de las 7 listas fuente
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.transport_coverage (
  id bigserial PRIMARY KEY,
  source text NOT NULL CHECK (source IN ('sede', 'retiro', 'expreso', 'credifin', 'snaider', 'via_cargo', 'mym')),
  provincia text NOT NULL,
  localidad text NOT NULL,
  transporte text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.transport_coverage IS
  '360: copia fiel de las listas de cobertura por transporte de '
  'client/transportes-data.js (y sus data/*.js), para que el bot de YCloud '
  'pueda consultarlas vía Data Connector. No es la fuente de verdad.';

ALTER TABLE public.transport_coverage ENABLE ROW LEVEL SECURITY;
CREATE POLICY transport_coverage_admin_all ON public.transport_coverage
  FOR ALL
  USING (EXISTS (SELECT 1 FROM public.admins a WHERE a.user_id = auth.uid()))
  WITH CHECK (EXISTS (SELECT 1 FROM public.admins a WHERE a.user_id = auth.uid()));

REVOKE ALL ON TABLE public.transport_coverage FROM PUBLIC;
REVOKE ALL ON TABLE public.transport_coverage FROM authenticated;
REVOKE ALL ON TABLE public.transport_coverage FROM anon;

-- ---------------------------------------------------------------------------
-- 2) Normalización de texto
-- ---------------------------------------------------------------------------

-- Mirror de normalize() en transportes-data.js (trim + lower + strip acentos,
-- SIN colapsar espacios internos): se usa para matchear provincia/localidad.
-- Nombre con prefijo fn_transport_coverage_ a propósito, para no competir
-- con public.normalize_transport_name / fn_normalize_transport_key (ya
-- existentes, usados por el módulo COD para nombres de TRANSPORTE, no de
-- provincia/localidad).
CREATE OR REPLACE FUNCTION public.fn_transport_coverage_normalize_locality(p_text text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path TO 'public', 'pg_catalog', 'extensions'
AS $$
  SELECT lower(trim(extensions.unaccent(coalesce(p_text, ''))));
$$;

-- Canonicalización de nombres de transporte: REUTILIZA
-- public.fn_canonicalize_transport_name (ya existente, usada por el módulo
-- COD), no se duplica acá.

CREATE INDEX IF NOT EXISTS idx_transport_coverage_lookup
  ON public.transport_coverage (source, public.fn_transport_coverage_normalize_locality(provincia), public.fn_transport_coverage_normalize_locality(localidad));

-- ---------------------------------------------------------------------------
-- 3) Función principal: mirror 1:1 de getTransportesDisponibles()
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fn_transportes_disponibles(p_provincia text, p_localidad text)
RETURNS text[]
LANGUAGE plpgsql
STABLE
SET search_path TO 'public', 'pg_catalog', 'extensions'
AS $$
DECLARE
  v_p text := public.fn_transport_coverage_normalize_locality(p_provincia);
  v_l text := public.fn_transport_coverage_normalize_locality(p_localidad);
  v_opciones text[] := '{}';
  v_final text[] := '{}';
  v_raw text;
  v_canonical text;
  v_item text;
BEGIN
  IF v_p = '' OR v_l = '' THEN
    RETURN '{}';
  END IF;

  -- SEDE: si la localidad está en destinos_transporte, solo se envía por SEDE.
  IF EXISTS (
    SELECT 1 FROM public.transport_coverage
    WHERE source = 'sede'
      AND public.fn_transport_coverage_normalize_locality(provincia) = v_p
      AND public.fn_transport_coverage_normalize_locality(localidad) = v_l
  ) THEN
    RETURN ARRAY['SEDE'];
  END IF;

  -- Corrientes Capital: solo Retira local + MyM (excluye Credifin/Snaider/Via Cargo/Correo).
  IF v_p = 'corrientes' AND v_l IN ('corrientes', 'corrientes capital') THEN
    RETURN ARRAY['Retira local', 'MyM'];
  END IF;

  -- Orden fijo: Retiro -> Expreso -> Credifin -> Transporte Snaider -> Via Cargo -> MyM.
  SELECT transporte INTO v_raw FROM public.transport_coverage
    WHERE source = 'retiro' AND public.fn_transport_coverage_normalize_locality(provincia) = v_p AND public.fn_transport_coverage_normalize_locality(localidad) = v_l LIMIT 1;
  IF v_raw IS NOT NULL THEN
    v_opciones := v_opciones || public.fn_canonicalize_transport_name(v_raw)::text;
  END IF;

  SELECT transporte INTO v_raw FROM public.transport_coverage
    WHERE source = 'expreso' AND public.fn_transport_coverage_normalize_locality(provincia) = v_p AND public.fn_transport_coverage_normalize_locality(localidad) = v_l LIMIT 1;
  IF v_raw IS NOT NULL THEN
    v_opciones := v_opciones || public.fn_canonicalize_transport_name(v_raw)::text;
  END IF;

  SELECT transporte INTO v_raw FROM public.transport_coverage
    WHERE source = 'credifin' AND public.fn_transport_coverage_normalize_locality(provincia) = v_p AND public.fn_transport_coverage_normalize_locality(localidad) = v_l LIMIT 1;
  IF v_raw IS NOT NULL THEN
    v_opciones := v_opciones || public.fn_canonicalize_transport_name(v_raw)::text;
  END IF;

  SELECT transporte INTO v_raw FROM public.transport_coverage
    WHERE source = 'snaider' AND public.fn_transport_coverage_normalize_locality(provincia) = v_p AND public.fn_transport_coverage_normalize_locality(localidad) = v_l LIMIT 1;
  IF v_raw IS NOT NULL THEN
    v_canonical := public.fn_canonicalize_transport_name(v_raw);
    IF NOT (v_canonical = ANY(v_opciones)) THEN
      v_opciones := v_opciones || v_canonical::text;
    END IF;
  END IF;

  SELECT transporte INTO v_raw FROM public.transport_coverage
    WHERE source = 'via_cargo' AND public.fn_transport_coverage_normalize_locality(provincia) = v_p AND public.fn_transport_coverage_normalize_locality(localidad) = v_l LIMIT 1;
  IF v_raw IS NOT NULL THEN
    v_canonical := public.fn_canonicalize_transport_name(v_raw);
    IF NOT (v_canonical = ANY(v_opciones)) THEN
      v_opciones := v_opciones || v_canonical::text;
    END IF;
  END IF;

  SELECT transporte INTO v_raw FROM public.transport_coverage
    WHERE source = 'mym' AND public.fn_transport_coverage_normalize_locality(provincia) = v_p AND public.fn_transport_coverage_normalize_locality(localidad) = v_l LIMIT 1;
  IF v_raw IS NOT NULL THEN
    v_canonical := public.fn_canonicalize_transport_name(v_raw);
    IF NOT (v_canonical = ANY(v_opciones)) THEN
      v_opciones := v_opciones || v_canonical::text;
    END IF;
  END IF;

  IF array_length(v_opciones, 1) IS NULL THEN
    v_opciones := ARRAY['Correo Argentino'];
  END IF;

  -- Dedupe preservando orden (canonicalizeTransportList en el JS).
  FOREACH v_item IN ARRAY v_opciones LOOP
    IF NOT (v_item = ANY(v_final)) THEN
      v_final := v_final || v_item::text;
    END IF;
  END LOOP;
  v_opciones := v_final;

  -- Si no hay SEDE en las opciones y no está Correo Argentino, se agrega como alternativa.
  IF NOT ('SEDE' = ANY(v_opciones)) AND array_length(v_opciones, 1) > 0 AND NOT ('Correo Argentino' = ANY(v_opciones)) THEN
    v_opciones := v_opciones || 'Correo Argentino'::text;
  END IF;

  RETURN v_opciones;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_transportes_disponibles(text, text) FROM PUBLIC;
