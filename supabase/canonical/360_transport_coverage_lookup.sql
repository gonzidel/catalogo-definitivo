-- 360_transport_coverage_lookup.sql
--
-- Data source para el bot "Asistente FYL" de YCloud (Data Connector, HTTPS
-- en vivo): responde "a qué localidad hacen envíos" con la MISMA cobertura
-- por transporte que ya usa la web (client/transportes-data.js). Los datos
-- de esta tabla son copia fiel y completa de las 7 listas fuente:
-- destinos_transporte (SEDE), retiro_del_local, expreso_norte,
-- CREDIFIN_PROVINCIAS (aplanado), viaCargoLocalities (via-cargo-localidades.js),
-- snaiderLocalities (snaider-localidades.js) y mym_cobertura. La función
-- fn_transportes_disponibles replica 1:1 el algoritmo de
-- getTransportesDisponibles(provincia, localidad) de transportes-data.js:
-- override SEDE, excepción Corrientes Capital (solo Retira local + MyM),
-- orden fijo retiro -> expreso -> credifin -> snaider -> via_cargo -> mym,
-- y fallback a Correo Argentino.
--
-- IMPORTANTE: ya existe infraestructura de canonicalización de nombres de
-- transporte para el módulo COD (public.fn_canonicalize_transport_name /
-- public.fn_normalize_transport_key, usadas por resolve_transport_id,
-- fn_closed_order_transport_category, etc., alineadas con
-- scripts/transport-canonical.js). Esta migración NO las duplica: reutiliza
-- esas mismas funciones para canonicalizar los nombres de esta tabla.
-- public.transports es solo el catálogo de 9 entidades transporte (con
-- duplicado histórico "Retira Local"/"Retiro de Local"); no tiene cobertura
-- por localidad, por eso esta tabla nueva no es redundante con esa.
--
-- Esta tabla es una COPIA para consulta del bot, no la fuente de verdad:
-- la fuente de verdad sigue siendo client/transportes-data.js y sus JS de
-- datos. Si esos archivos cambian, esta tabla debe volver a sincronizarse
-- (no hay trigger de sincronización automática todavía).
--
-- Ver docs/FYL-Obsidian/68-CRM-AUTOMATICO-YCLOUD-2026-09-23.md (sección del
-- chatbot Asistente FYL) para el resto del trabajo de revisión del bot.
--
-- Rollback: 360_ROLLBACK_transport_coverage_lookup.sql
-- Tests: 360_transport_coverage_lookup_tests.sql

-- ---------------------------------------------------------------------------
-- 0) Extensión unaccent (mismo patrón que 181_purchase_suppliers_module.sql)
